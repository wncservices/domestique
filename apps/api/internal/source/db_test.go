// openTestDB opens a SQLite database. Most tests use this; TestEachEngine runs
// the behavioural suite against PostgreSQL as well.
func openTestDB(t *testing.T) *DB {
	t.Helper()
	db, err := OpenDB(filepath.Join(t.TempDir(), "test.db"))
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	t.Cleanup(func() { db.Close() })
	return db
}

// openTestPostgres opens a PostgreSQL schema of its own (see internal/pgtest).
//
// PostgreSQL is what this runs against in the cluster, so "it works on SQLite"
// is not enough: placeholders, the boolean column and the blob type all differ.
// Set DOMESTIQUE_TEST_POSTGRES to a DSN to include it; CI does.
func openTestPostgres(t *testing.T) *DB {
	t.Helper()

	dsn := pgtest.DSN(t)

	db, err := OpenDB(dsn)
	if err != nil {
		t.Fatalf("open postgres: %v", err)
	}
	// Each test gets a clean table; they share one database.
	if _, err := db.db.Exec(`DROP TABLE IF EXISTS routes`); err != nil {
		t.Fatalf("reset schema: %v", err)
	}
	if _, err := db.db.Exec(routesSchema(db.dialect)); err != nil {
		t.Fatalf("recreate schema: %v", err)
	}

	t.Cleanup(func() { db.Close() })
	return db
}

func exampleGPX(t *testing.T) []byte {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", "kemmelberg-loop.gpx"))
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func TestDBCreateDerivesStatsAndSlug(t *testing.T) {
	db := openTestDB(t)

	route, err := db.Create(t.Context(), CreateRequest{
		Filename: "kemmelberg-loop.gpx",
		GPX:      exampleGPX(t),
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}

	if route.Slug != "kemmelberg-loop" {
		t.Errorf("slug = %q, want kemmelberg-loop derived from the filename", route.Slug)
	}
	if route.Name != "Kemmelberg Loop" {
		t.Errorf("name = %q, want a titleized filename", route.Name)
	}
	if route.Stats.PointCount == 0 || route.Stats.DistanceM == 0 {
		t.Errorf("stats not derived on upload: %+v", route.Stats)
	}
	if route.ContentHash == "" {
		t.Error("content hash not computed; the diff engine would never see a change")
	}
}

// A rider's real description must survive the cleanup; only the app's own
// auto-generated sentence gets blanked, and only on a genuine reopen (a
// second process startup against the same file) — not retroactively wiped
// out from under an already-running one.
func TestOpenDBClearsOnlyAutoGeneratedDescriptions(t *testing.T) {
	path := filepath.Join(t.TempDir(), "test.db")
	db, err := OpenDB(path)
	if err != nil {
		t.Fatalf("open db: %v", err)
	}

	imported, err := db.Create(t.Context(), CreateRequest{
		Name: "Old Komoot Import", Descript: "Imported from Komoot (tour 2030514247)", GPX: exampleGPX(t),
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	synced, err := db.Create(t.Context(), CreateRequest{
		Name: "Old Garmin Sync", Descript: "Synced back from Garmin (course 454821206)", GPX: exampleGPX(t),
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	real, err := db.Create(t.Context(), CreateRequest{
		Name: "Hand-Written", Descript: "My favourite loop through the Ardennes", GPX: exampleGPX(t),
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	db.Close()

	reopened, err := OpenDB(path)
	if err != nil {
		t.Fatalf("reopen db: %v", err)
	}
	defer reopened.Close()

	routes, _, err := reopened.List(t.Context())
	if err != nil {
		t.Fatalf("list: %v", err)
	}
	byName := map[string]string{}
	for _, r := range routes {
		byName[r.Name] = r.Description
	}
	if byName[imported.Name] != "" {
		t.Errorf("Komoot description = %q, want cleared", byName[imported.Name])
	}
	if byName[synced.Name] != "" {
		t.Errorf("Garmin description = %q, want cleared", byName[synced.Name])
	}
	if byName[real.Name] != "My favourite loop through the Ardennes" {
		t.Errorf("hand-written description = %q, want it untouched", byName[real.Name])
	}
}

// UploadedBy and a claimed/reassigned Owner both get normalized the same
// way identityFromToken already normalizes every OIDC claim — otherwise a
// route's owner and its owner's own crew membership (internal/crew applies
// the identical normalization) can end up spelled differently for the same
// real rider, and crew.MemberSet.Has — even case-insensitively — still has
// nothing to fall back on for genuinely garbled input like extra whitespace
// this at least prevents outright.
func TestDBNormalizesOwnerCasing(t *testing.T) {
	db := openTestDB(t)

	created, err := db.Create(t.Context(), CreateRequest{
		Name: "Case Test", UploadedBy: "  Wilant  ", GPX: exampleGPX(t),
	})
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	if created.Owner != "wilant" {
		t.Fatalf("owner = %q, want normalized to wilant", created.Owner)
	}

	claimed := "  TIEBE  "
	updated, err := db.Update(t.Context(), created.Slug, UpdateRequest{Owner: &claimed})
	if err != nil {
		t.Fatalf("update: %v", err)
	}
	if updated.Owner != "tiebe" {
		t.Fatalf("owner after update = %q, want normalized to tiebe", updated.Owner)
	}
}

